const AGUDO: Filas = ["00010", "00100"];
const DIERESIS: Filas = ["01010", "00000"];
const VIRGULILLA: Filas = ["01101", "10110"];
const SIN_ACENTO: Filas = ["00000", "00000"];

/** Letra con acento → [acento, letra base]. La "í" pierde el punto: lo sustituye la tilde. */
const ACENTUADAS: Record<string, [Filas, Filas]> = {
  "Á": [AGUDO, G["A"]!], "É": [AGUDO, G["E"]!], "Í": [AGUDO, G["I"]!], "Ó": [AGUDO, G["O"]!],
  "Ú": [AGUDO, G["U"]!], "Ñ": [VIRGULILLA, G["N"]!], "Ü": [DIERESIS, G["U"]!],
  "á": [AGUDO, G["a"]!], "é": [AGUDO, G["e"]!], "ó": [AGUDO, G["o"]!], "ú": [AGUDO, G["u"]!],
  "í": [AGUDO, ["00000", "00000", "01100", "00100", "00100", "00100", "01110"]],
  "ñ": [VIRGULILLA, G["n"]!], "ü": [DIERESIS, G["u"]!],
};

export const GLYPH_W = 5;
export const GLYPH_H = 9;
/** Ancho de una letra más su separación, en píxeles de la fuente. */
export const ADVANCE = GLYPH_W + 1;

/** Las 9 filas de un carácter: 2 de acento y 7 de letra. */
function glifo(ch: string): readonly string[] {
  const acentuada = ACENTUADAS[ch];
  if (acentuada) return [...acentuada[0], ...acentuada[1]];
  // Las comillas y guiones tipográficos se pintan con su equivalente simple.
  const simple = ({ "–": "-", "—": "-", "’": "'", "‘": "'", "“": "\"", "”": "\"" } as Record<string, string>)[ch];
  return [...SIN_ACENTO, ...(G[simple ?? ch] ?? G["?"]!)];
}

export function hasGlyph(ch: string): boolean {
  return ch in G || ch in ACENTUADAS || "–—’‘“”".includes(ch);
}

type Color = readonly [number, number, number];

/**
 * Pinta `texto` con su esquina superior izquierda en (x, y). `escala` es
 * cuántos píxeles de la imagen mide cada píxel de la fuente. `negrita` lo
 * pinta dos veces, desplazado uno: es como la hace una impresora de tickets.
 */
export function drawText(
  lienzo: Lienzo, texto: string, x: number, y: number, escala: number, color: Color, negrita = false,
): void {
  let cx = x;
  for (const ch of texto) {
    const filas = glifo(ch);
    for (let fy = 0; fy < GLYPH_H; fy++) {
      for (let fx = 0; fx < GLYPH_W; fx++) {
        if (filas[fy]![fx] !== "1") continue;
        lienzo.rect(cx + fx * escala, y + fy * escala, escala, escala, color);
        if (negrita) lienzo.rect(cx + fx * escala + Math.max(1, escala >> 1), y + fy * escala, escala, escala, color);
      }
    }
    cx += ADVANCE * escala;
  }
}

/** Ancho en píxeles de la imagen de un texto a esa escala. */
export function textWidth(texto: string, escala: number): number {
  return [...texto].length * ADVANCE * escala;
}
